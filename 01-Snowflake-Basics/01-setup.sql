
-- Snowflake in 20 Minutes
-- Step 1: Create database and table

CREATE DATABASE IF NOT EXISTS SF_TUTS;

USE DATABASE SF_TUTS;
USE SCHEMA PUBLIC;

CREATE TABLE IF NOT EXISTS EMP_BASIC (
    FIRST_NAME STRING,
    LAST_NAME STRING,
    EMAIL STRING,
    STREETADDRESS STRING,
    CITY STRING,
    START_DATE DATE
);

-- Step 2: Create virtual warehouse

CREATE WAREHOUSE IF NOT EXISTS SF_TUTS_WH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 180
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SF_TUTS_WH;
